#pragma once

#include <stdint.h>

// 5×8 点阵字模。每个字符 8 行，每行低 5 位有效，bit4 = 最左那个像素。
//
// 手写而不是引字体库：一共只用得上 10 个数字加一个百分号，为这点东西拖一个
// 字体依赖不划算。也不画中文 —— 电量槽只有 72×30，塞不下汉字，中文文案由
// 服务器在渲染照片时就烧进图里了。
//
// 字模偏"2 太小/0 太圆"之类的观感问题，改这里就行，不影响别处。

constexpr int GLYPH_W = 5;
constexpr int GLYPH_H = 8;
constexpr int GLYPH_ADVANCE = GLYPH_W + 1;   // 字间距 1px

// 索引：0..9 → '0'..'9'，10 → '%'，11 → '-'（电量计读不到时显示 "--"）
//
// ⚠️ 表里没有的字符，drawGlyph 会【跳过不画但照样占位】。所以 "--" 这种占位符
//    必须有对应字形 —— 否则布局留了 11px 空白、屏上却一个字都没有，
//    看着像"没电"而不是"没读到"。
//
// 用 static 而不是 inline：Arduino ESP32 核心默认是 gnu++11，inline 变量要 C++17。
// 为这几十个字节把整个工程的标准抬上去不划算，让它每个编译单元各留一份就是了。
static constexpr uint8_t kGlyphs5x8[12][8] = {
    {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E, 0x00},  // 0
    {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E, 0x00},  // 1
    {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F, 0x00},  // 2
    {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E, 0x00},  // 3
    {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02, 0x00},  // 4
    {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E, 0x00},  // 5
    {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E, 0x00},  // 6
    {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08, 0x00},  // 7
    {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E, 0x00},  // 8
    {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C, 0x00},  // 9
    // % ：左上小方块 + 左下到右上的斜线 + 右下小方块。
    // 曾经写成 0x19,0x1A,0x02,0x04,0x08,0x0B,0x13 —— 最后两行多了左边的位，
    // 画出来是个「Z」不是「%」。
    {0x19, 0x1A, 0x04, 0x08, 0x10, 0x03, 0x03, 0x00},  // %
    {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00, 0x00},  // -
};

// 找不到字形返回 -1（调用方应当跳过，而不是画个方块）
inline int glyphIndex(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  if (c == '%') return 10;
  if (c == '-') return 11;
  return -1;
}

// 一串字符占的像素宽度（含字间距，不含末尾那个间距）
inline int glyphTextWidth(const char* s) {
  int n = 0;
  for (const char* p = s; *p; ++p) ++n;
  return n > 0 ? n * GLYPH_ADVANCE - 1 : 0;
}
